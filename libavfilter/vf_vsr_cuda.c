/* Generated by rtx-video-re from the proprietary NVIDIA library, and
 * installed rather than carried here -- located, together with the cubins and
 * weights it names, through pkg-config (see configure's nvfdata_* checks). */
#include <vsr_cuda_gen.h>

FF_RTX_ASSERT_MODULE_LAYOUT(VsrModule);
FF_RTX_ASSERT_FUNC_LAYOUT(VsrFunc);
FF_RTX_ASSERT_UPLOAD_LAYOUT(VsrGenUpload);
FF_RTX_ASSERT_LAUNCH_LAYOUT(VsrGenLaunch);

typedef struct VsrCudaContext {
    const AVClass *class;

    FFRtxCuda   r;
    FFRtxImage *in_img, *out_img;

    int W, H, oW, oH;                 ///< input / output size
    int cfg;                          ///< index into vsr_configs

    const FFRtxPixFmt *inpf, *outpf;  ///< input / output packed-RGB descriptors

    /* options */
    int   quality;
    int   scale;                      ///< native SR factor for q3/q4: 0=auto(from ratio), 2/3/4=forced
    char *w_expr;
    char *h_expr;
    char *data_dir;
    char *out_format;
} VsrCudaContext;

#define OFFSET(x) offsetof(VsrCudaContext, x)
#define FLAGS (AV_OPT_FLAG_VIDEO_PARAM | AV_OPT_FLAG_FILTERING_PARAM)

static const AVOption vsr_cuda_options[] = {
    { "quality", "VSR quality/model (0=bicubic 1=low 2=medium 3=high 4=ultra; 5=denoise 6=deblur are 1x restoration-only; 7=lossless)", OFFSET(quality), AV_OPT_TYPE_INT, {.i64=1}, 0, 7, FLAGS },
    /* Native integer SR factor for the scale-adaptive high/ultra models (quality
     * 3/4); ignored for the fixed-2x models.  0 = auto: derive the internal
     * pixel_shuffle from the output/input ratio (ps = min(ceil(max(ratio)),4)),
     * matching the snippet.  2/3/4 = force that native pixel_shuffle2/3/4 head,
     * independent of the requested output size -- so you can run e.g. the ultra 4x
     * network and then resample its result to any 'w'x'h'. */
    { "scale", "native integer SR factor for quality 3/4 (0=auto, 2/3/4=forced)", OFFSET(scale), AV_OPT_TYPE_INT, {.i64=0}, 0, 4, FLAGS },
    /* Output size.  Unset (default) = the native scale x input: quality 3/4 with a
     * forced 'scale' -> that factor, everything else -> 2x.  Set either to any
     * expression for arbitrary output; a non-native ratio resamples the native
     * result to the requested rect. */
    { "w", "output width expression (default: native scale x input)",  OFFSET(w_expr), AV_OPT_TYPE_STRING, {.str=NULL}, 0, 0, FLAGS },
    { "h", "output height expression (default: native scale x input)", OFFSET(h_expr), AV_OPT_TYPE_STRING, {.str=NULL}, 0, 0, FLAGS },
    { "data", "directory with extracted VSR cubins + the shared weights.bin",
      OFFSET(data_dir), AV_OPT_TYPE_STRING, {.str=VSR_DEFAULT_DATA_DIR}, 0, 0, FLAGS },
    { "format", "output pixel format (empty = same as input); e.g. bgra, rgba64le",
      OFFSET(out_format), AV_OPT_TYPE_STRING, {.str=NULL}, 0, 0, FLAGS },
    { NULL }
};

