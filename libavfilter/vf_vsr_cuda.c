/**
 * @file
 * Super-resolution filter driving NVIDIA RTX Video Super Resolution.  The VSR
 * network ships as a "pure CUDA" graph inside nvngx_vsr.dll; the cubins were
 * extracted per-architecture and the forward pass reverse-engineered by
 * intercepting the live CUDA Driver-API launches.  vsr_cuda_gen.h encodes, per
 * quality (0-4) and per scaling path, how the whole graph (grids, scratch
 * allocations, packed arg-buffer scalars incl. division-magic constants and
 * float32 resample steps, weight-upload targets, pointer fixups) scales with the
 * input W,H and output oW,oH -- derived and validated byte-exact against the DLL
 * (rtx-video-re).  The filter evaluates that at config time and then just
 * replays the graph with libcuda; no DLL is needed at run time.  The replay
 * machinery itself is rtx_cuda.c.
 *
 * Most models perform a fixed internal 2x super-resolution: exact isotropic 2x
 * output takes the "fast" path (direct postProcess); any other factor (non-integer,
 * downscale, anisotropic) takes the "resample" path (bicubic compose to the
 * requested rect).  The high/ultra models (quality 3/4) are scale-adaptive: their
 * SR block selects an internal pixel_shuffle factor ps = min(ceil(max(oW/W,oH/H)),4)
 * and writes natively (postProcess) for an isotropic-exact integer 2x/3x/4x, else
 * resamples with that ps.  Each (quality, path, factor) is a separate config.
 *
 * The 'scale' option (q3/q4 only) decouples that internal factor from the output
 * size: scale=0 (default) derives ps from the requested ratio (byte-exact with the
 * snippet), while scale=2/3/4 forces the pixel_shuffle2/3/4 head and defaults the
 * output to scale x input.  Setting w/h as well runs the chosen native-Nx network
 * and resamples its result to that rect -- e.g. scale=4 with a 1080p output runs
 * the 4x network then downscales, independent of the 3x the ratio would imply.
 *
 * Quality 5=denoise and 6=deblur are native-resolution RESTORATION networks, not
 * upscalers: they are forced to 1x (output = input size) because any upscale makes
 * them emit a checkerboard / chroma hallucination.  Restore with them first, then
 * upscale with a separate quality=3/4 pass.  (7=lossless is a faithful pass-through
 * and is left unconstrained.)
 *
 * I/O binding mirrors the DLL: the input frame is bound as a bindless TEXTURE
 * (UNSIGNED_INT8 x4, clamp/linear/normalized -> samples in [0,1]) and the output as
 * a bindless SURFACE over a CUDA array.  The captured arg blocks carry the tex/surf
 * handles at known offsets, which we patch to our own objects.
 *
 * The cubins and the shared weights blob are external files (the "data"
 * option), as for every filter in this family: they are extracted from the
 * proprietary DLL and are not shipped with FFmpeg.  Input/output are packed RGB
 * CUDA frames: 8-bit rgb0/bgr0/rgba/bgra or 16-bit rgba64le.
 */

