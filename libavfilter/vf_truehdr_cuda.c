/* Generated by rtx-video-re from the proprietary NVIDIA library, and
 * installed rather than carried here -- located, together with the cubins and
 * weights it names, through pkg-config (see configure's nvfdata_* checks). */
#include <truehdr_cuda_gen.h>

FF_RTX_ASSERT_MODULE_LAYOUT(ThdrModule);
FF_RTX_ASSERT_FUNC_LAYOUT(ThdrFunc);
FF_RTX_ASSERT_UPLOAD_LAYOUT(ThdrGenUpload);
FF_RTX_ASSERT_LAUNCH_LAYOUT(ThdrGenLaunch);

/* Input: R-first 8-bit or 10-bit x2bgr10le (no B-first path). Output: HDR fp16 or 10-bit. */
static const FFRtxPixFmt thdr_in_fmts[] = {
    { AV_PIX_FMT_RGB0,      CU_AD_FORMAT_UNSIGNED_INT8,       4, 0 },
    { AV_PIX_FMT_RGBA,      CU_AD_FORMAT_UNSIGNED_INT8,       4, 0 },
    { AV_PIX_FMT_X2BGR10LE, CU_AD_FORMAT_UNORM_INT_101010_2,  4, 0 },
};
static const FFRtxPixFmt thdr_out_fmts[] = {
    { AV_PIX_FMT_RGBAF16LE, CU_AD_FORMAT_HALF,                8, 0 },
    { AV_PIX_FMT_X2BGR10LE, CU_AD_FORMAT_UNORM_INT_101010_2,  4, 1 },
};

typedef struct TrueHdrCudaContext {
    const AVClass *class;

    FFRtxCuda   r;
    FFRtxImage *in_img;               ///< pitched linear memory (PITCH2D texture, as in the DLL)
    FFRtxImage *out_img;              ///< HDR output array + surface
    FFRtxImage *scratch;              ///< dedicated clear-target for truehdr_postprocessing
    FFRtxImage *zero;                 ///< reads 0: bound to stale intermediate-texture handles

    int W, H;                         ///< input == output size

    const FFRtxPixFmt *inpf, *outpf;

    /* options */
    double contrast, saturation, middlegray, maxluminance;
    char  *data_dir;
    char  *out_format;
} TrueHdrCudaContext;

#define OFFSET(x) offsetof(TrueHdrCudaContext, x)
#define FLAGS (AV_OPT_FLAG_VIDEO_PARAM | AV_OPT_FLAG_FILTERING_PARAM)

static const AVOption truehdr_cuda_options[] = {
    { "contrast", "contrast (0..200)", OFFSET(contrast), AV_OPT_TYPE_DOUBLE, {.dbl=100}, 0, 200, FLAGS },
    { "saturation", "saturation (0..200)", OFFSET(saturation), AV_OPT_TYPE_DOUBLE, {.dbl=100}, 0, 200, FLAGS },
    { "middlegray", "middle gray (10..100)", OFFSET(middlegray), AV_OPT_TYPE_DOUBLE, {.dbl=50}, 10, 100, FLAGS },
    { "maxluminance", "peak luminance in nits (400..2000)", OFFSET(maxluminance), AV_OPT_TYPE_DOUBLE, {.dbl=1000}, 400, 2000, FLAGS },
    { "data", "directory with extracted TrueHDR cubins + weights.bin",
      OFFSET(data_dir), AV_OPT_TYPE_STRING, {.str=TRUEHDR_DEFAULT_DATA_DIR}, 0, 0, FLAGS },
    /* Named default so `format` reports what it does (no same-as-input output here). */
    { "format", "output: rgbaf16le=scRGB linear Rec.709 80nit (default), x2bgr10le=HDR10 PQ Rec.2020",
      OFFSET(out_format), AV_OPT_TYPE_STRING, {.str="rgbaf16le"}, 0, 0, FLAGS },
    { NULL }
};

AVFILTER_DEFINE_CLASS(truehdr_cuda);

FF_RTX_ASSERT_PRIV_LAYOUT(TrueHdrCudaContext);

/* Capture yields only one GPU's images; `rtxv extract` repacks as multi-arch fatbins. */
#define THDR_LOAD_HINT \
    "Re-run `rtxv extract truehdr <nvngx_truehdr.dll>` and `rtxv install`: the " \
    "generator repacks each kernel as the snippet's own multi-arch fatbin."

static void fill_sizes(AVFilterContext *ctx, long long *sz)
{
    TrueHdrCudaContext *s = ctx->priv;
    int NW, NH;
    ff_rtx_nn_dims(s->W, s->H, &NW, &NH);
    thdr_fill_allocs(s->W, s->H, NW, NH, sz);
}

static int setup_graph(AVFilterContext *ctx)
{
    TrueHdrCudaContext *s = ctx->priv;
    ThdrGenUpload *up;
    thdr_devptr handle[5] = { 0 };
    int W = s->W, H = s->H, NW, NH, ret, nup;

    ff_rtx_nn_dims(W, H, &NW, &NH);

    if ((ret = ff_rtx_load_modules(ctx, &s->r, s->data_dir,
                                   (const FFRtxModule *)thdr_modules, THDR_NMODULE, THDR_MAX_MID,
                                   (const FFRtxFunc *)thdr_funcs, THDR_NFUNC, THDR_MAX_FID,
                                   THDR_LOAD_HINT)) < 0)
        return ret;
    /* Zero the arena: conv/pov kernels read scratch before writing. */
    if ((ret = ff_rtx_alloc_arena(ctx, &s->r, THDR_NALLOC, fill_sizes,
                                  FF_RTX_ARENA_ZERO)) < 0)
        return ret;

    up = av_calloc(THDR_NUPLOAD, sizeof(*up));
    if (!up)
        return AVERROR(ENOMEM);
    nup = thdr_fill_uploads(W, H, NW, NH, (const thdr_devptr *)s->r.alloc, up);
    ret = ff_rtx_upload_weights(ctx, &s->r, s->data_dir, "weights.bin",
                                (const FFRtxUpload *)up, nup);
    av_freep(&up);
    if (ret < 0)
        return ret;

    /* Snapshot pristine arena; reset from it each frame for clean scratch. */
    if ((ret = ff_rtx_snapshot_arena(ctx, &s->r)) < 0)
        return ret;

    s->in_img = ff_rtx_image_pitch(ctx, &s->r, W, H, s->inpf->cufmt, s->inpf->bpp,
                                   FF_RTX_TEX | FF_RTX_CLAMP);
    /* Zero texture for stale intermediate handles (kind-4 fixups): clamped read -> always 0. */
    s->zero = ff_rtx_image_pitch(ctx, &s->r, 64, 64, s->inpf->cufmt, s->inpf->bpp,
                                 FF_RTX_TEX | FF_RTX_CLAMP | FF_RTX_ZERO);
    s->out_img = ff_rtx_image_array(ctx, &s->r, W, H, s->outpf->cufmt,
                                    FF_RTX_SURF | FF_RTX_LDST);
    /* Scratch surface for stale handle writes (kind-3 fixups): nothing reads them back. */
    s->scratch = ff_rtx_image_array(ctx, &s->r, W, H, CU_AD_FORMAT_UNSIGNED_INT32,
                                    FF_RTX_SURF | FF_RTX_LDST);
    if (!s->in_img || !s->zero || !s->out_img || !s->scratch)
        return AVERROR_EXTERNAL;

    /* Build the graph: kinds 3/4 route stale handles to private objects. */
    if ((ret = ff_rtx_alloc_launches(ctx, &s->r, THDR_NLAUNCH, sizeof(ThdrGenLaunch))) < 0)
        return ret;
    handle[3] = (thdr_devptr)s->scratch->surf;
    handle[4] = (thdr_devptr)s->zero->tex;
    if (thdr_fill_graph(W, H, NW, NH, (const thdr_devptr *)s->r.alloc,
                        (thdr_devptr)s->in_img->tex, (thdr_devptr)s->out_img->surf,
                        handle, s->r.launches) != THDR_NLAUNCH) {
        av_log(ctx, AV_LOG_ERROR, "generated fill disagrees with the tables\n");
        return AVERROR_BUG;
    }

    /* drtm overrides: tunables and output-format flags at fixed arg offsets. */
    if (THDR_DRTM_LAUNCH < 0 || THDR_DRTM_LAUNCH >= s->r.nlaunch) {
        av_log(ctx, AV_LOG_ERROR, "no drtm launch in graph\n");
        return AVERROR_BUG;
    }
    {
        uint8_t *a = ff_rtx_launch_at(&s->r, THDR_DRTM_LAUNCH)->params;
        float contrast   = (float)(0.45 + 0.004 * av_clipd(s->contrast,   0, 200));
        float saturation = (float)(0.85 + 0.002 * av_clipd(s->saturation, 0, 200));
        float middlegray = (float)av_clipd(s->middlegray,   10, 100);
        float maxlum     = (float)av_clipd(s->maxluminance, 400, 2000);
        uint32_t flag    = (uint32_t)s->outpf->sel;
        memcpy(a + THDR_OFF_CONTRAST,     &contrast,   4);
        memcpy(a + THDR_OFF_SATURATION,   &saturation, 4);
        memcpy(a + THDR_OFF_MIDDLEGRAY,   &middlegray, 4);
        memcpy(a + THDR_OFF_MAXLUMINANCE, &maxlum,     4);
        memcpy(a + THDR_OFF_OUTFLAG0,     &flag,       4);
        memcpy(a + THDR_OFF_OUTFLAG1,     &flag,       4);
    }

    av_log(ctx, AV_LOG_INFO,
           "TrueHDR graph ready: %dx%d (NN %dx%d)  %s -> %s  (%d launches, %d buffers)\n",
           W, H, NW, NH, av_get_pix_fmt_name(s->inpf->f), av_get_pix_fmt_name(s->outpf->f),
           s->r.nlaunch, s->r.nalloc);
    return 0;
}

/* Retag output as HDR (scRGB or HDR10 PQ/Rec.2020). */
static void retag_hdr(AVFilterContext *ctx, AVFrame *out)
{
    TrueHdrCudaContext *s = ctx->priv;

    out->colorspace     = AVCOL_SPC_RGB;
    out->color_range    = AVCOL_RANGE_JPEG;
    if (s->outpf->f == AV_PIX_FMT_X2BGR10LE) {
        out->color_primaries = AVCOL_PRI_BT2020;
        out->color_trc       = AVCOL_TRC_SMPTE2084;
    } else {                                  /* rgbaf16le scRGB */
        out->color_primaries = AVCOL_PRI_BT709;
        out->color_trc       = AVCOL_TRC_LINEAR;
    }
}

static int filter_frame(AVFilterLink *inlink, AVFrame *in)
{
    TrueHdrCudaContext *s = inlink->dst->priv;
    const FFRtxFrameOp op = {
        .in_img = s->in_img,   .iW = s->W, .iH = s->H, .ibpp = s->inpf->bpp,
        .out_img = s->out_img, .oW = s->W, .oH = s->H, .obpp = s->outpf->bpp,
        /* Reset the arena each frame: the DLL gets fresh memory per frame, we
         * reuse one arena, and a long-running host recycles it dirty. */
        .flags = FF_RTX_OP_RESET_ARENA,
    };

    return ff_rtx_filter_frame(inlink, in, &s->r, &op, retag_hdr);
}

static int config_output(AVFilterLink *outlink)
{
    AVFilterContext *ctx = outlink->src;
    AVFilterLink *inlink = ctx->inputs[0];
    TrueHdrCudaContext *s = ctx->priv;
    AVHWFramesContext *in_frames_ctx;
    FFRtxFormats fmts = {
        .in_tbl  = thdr_in_fmts, .n_in  = FF_ARRAY_ELEMS(thdr_in_fmts),
        .out_tbl = thdr_out_fmts, .n_out = FF_ARRAY_ELEMS(thdr_out_fmts),
        .hint    = "use rgb0/rgba in, rgbaf16le/x2bgr10le out",
    };
    int ret;

    ff_rtx_free_graph(ctx, &s->r);

    fmts.out_format = s->out_format;
    if ((ret = ff_rtx_config_formats(ctx, inlink, &fmts, &in_frames_ctx,
                                     &s->inpf, &s->outpf)) < 0)
        return ret;

    s->W = inlink->w;
    s->H = inlink->h;

    if ((ret = ff_rtx_bind_device(ctx, &s->r, in_frames_ctx)) < 0)
        return ret;
    if ((ret = ff_rtx_config_hwframes(ctx, outlink, &s->r, s->W, s->H,
                                      s->outpf->f)) < 0)
        return ret;
    return ff_rtx_setup(ctx, &s->r, "TrueHDR", setup_graph);
}

