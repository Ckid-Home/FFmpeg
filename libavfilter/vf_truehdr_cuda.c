/**
 * @file
 * Inverse tone-mapping (SDR -> HDR) filter driving NVIDIA RTX TrueHDR.  Like
 * vf_vsr_cuda, the network ships as a "pure CUDA" graph inside
 * nvngx_truehdr.dll; the cubins were extracted per-architecture and the forward
 * pass reverse-engineered by intercepting the live CUDA Driver-API launches.
 * truehdr_cuda_gen.h encodes how the whole graph (grids, scratch allocations,
 * packed arg-buffer scalars, weight-upload targets, pointer fixups) scales with
 * the input W,H -- derived and validated byte-exact against the DLL
 * (rtx-video-re).  The filter evaluates that at config time and replays the
 * graph with libcuda; no DLL is needed at run time.  The replay machinery itself
 * is rtx_cuda.c.
 *
 * Unlike VSR, TrueHDR does NOT rescale: output resolution == input resolution.
 * The neural core runs at an internal resolution NW x NH derived from the input
 * aspect ratio (ff_rtx_nn_dims); calculate_pov / postprocessing / drtm run at the
 * input resolution.  The four tunables (contrast, saturation, middle-gray, peak
 * luminance) and the output-format selection are small orthogonal overrides
 * written into the final truehdr_drtm launch's arg buffer.
 *
 * I/O binding mirrors the DLL: the input frame is bound as a bindless TEXTURE
 * (PITCH2D, clamp/linear/normalized -> samples in [0,1], format-agnostic) and
 * the HDR output as a bindless SURFACE over a CUDA array.  Input is 8-bit
 * rgb0/rgba (R-first; TrueHDR has no R<->B swap path) -- the standard SDR case --
 * or 10-bit x2bgr10le; the format-agnostic texture read normalizes any of them.
 *
 * The two output formats are DIFFERENT COLOR SPACES, not just bit depths (the
 * drtm arg words at off 68/72 select gamut and transfer; decoded from the drtm
 * PTX and confirmed byte-exact, see rtx-video-re docs/FINDINGS-truehdr.md):
 *   - rgbaf16le (default) = scRGB: linear light, Rec.709 primaries, 1.0 = 80 nits
 *     (the Windows HDR swapchain format).
 *   - x2bgr10le           = HDR10 / BT.2100: PQ (SMPTE ST.2084) transfer, Rec.2020
 *     primaries -- i.e. already display-ready HDR10; no tone/gamut conversion, just
 *     tag bt2020/pq/bt2020nc and do the RGB->YUV matrix to feed an HDR10 encoder.
 * (10-bit x2bgr10le input is also accepted and byte-exact vs the DLL/replayer.
 * An earlier top-left-corner divergence turned out to be the old CUarray input
 * binding; the PITCH2D binding above -- which matches the DLL -- is byte-exact
 * for 10-bit input across sizes incl. padded pitch.  See rtx-video-re
 * docs/FINDINGS-truehdr.md.)
 *
 * The cubins and per-config weights blob are external files (the "data"
 * option), extracted from the proprietary DLL and not shipped with FFmpeg.
 */

